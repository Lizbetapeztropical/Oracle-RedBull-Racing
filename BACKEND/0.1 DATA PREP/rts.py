# Encontramos el tiempo mínimo (vuelta más rápida) por carrera y piloto
fastest_by_lap = lt.groupby(['RACEID', 'DRIVERID'])['MILLISECONDS'].min().reset_index()

# Función para convertir MS a formato de tiempo (MM:SS.mmm)
def ms_to_f1_format(ms):
    if pd.isna(ms) or ms == 0: return np.nan
    minutes = int(ms // 60000)
    seconds = (ms % 60000) / 1000
    return f"{minutes:02d}:{seconds:06.3f}"[:-1]

fastest_by_lap['TIME_CALCULATED'] = fastest_by_lap['MILLISECONDS'].apply(ms_to_f1_format)

# 3. PROCESAMIENTO DE FASTESTLAPSPEED (Opción B: Promedio por carrera)
# Calculamos el promedio de velocidad de los que SÍ tienen dato en cada carrera
race_speed_avg = rts.groupby('RACEID')['FASTESTLAPSPEED'].transform('mean')

# 4. MERGE E IMPUTACIÓN
# Unimos los tiempos calculados de LAP_TIMES
