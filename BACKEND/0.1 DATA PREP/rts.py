lt['MILLISECONDS'] = pd.to_numeric(lt['MILLISECONDS'], errors='coerce')

# Convertir MILLISECONDS de rts a numérico. Los valores '\N' ya se manejaron antes y se imputaron con 0 o nan.
rts['MILLISECONDS'] = pd.to_numeric(rts['MILLISECONDS'], errors='coerce')

# 2. CALCULAR EL TIEMPO ACUMULADO REAL EN LAP_TIMES
# Sumamos todos los milisegundos que existan para cada par Piloto-Carrera
# Sin importar si terminó la carrera o no, sumamos lo que haya.
tiempos_acumulados = lt.groupby(['RACEID', 'DRIVERID'])['MILLISECONDS'].sum().reset_index()
tiempos_acumulados.rename(columns={'MILLISECONDS': 'MS_TOTAL_LT'}, inplace=True)

# 3. HACER EL JOIN
# Traemos esa suma a la tabla RESULTS (rts)
rts = rts.merge(tiempos_acumulados, on=['RACEID', 'DRIVERID'], how='left')

# 4. RELLENO MASIVO
# Si el original es nulo, usamos la suma de todas las vueltas encontradas en LAP_TIMES
rts['MILLISECONDS'] = rts['MILLISECONDS'].fillna(rts['MS_TOTAL_LT'])

# 5. EL PARCHE FINAL (Lógica de Negocio)
# Para los casos que siguen siendo nulos tras el join (porque no existen en LAP_TIMES),
# la única forma de tener 0 nulos es imputar por el desempeño de la carrera.
# Usamos el promedio de milisegundos por vuelta de esa carrera multiplicado por las vueltas del piloto.

# Calculamos el tiempo promedio por vuelta de cada carrera (usando los datos que sí tenemos)
avg_lap_ms = rts[rts['MILLISECONDS'] > 0].groupby('RACEID')['MILLISECONDS'].sum() / \
             rts[rts['MILLISECONDS'] > 0].groupby('RACEID')['LAPS'].sum()
avg_lap_ms = avg_lap_ms.reset_index().rename(columns={0: 'AVG_MS_PER_LAP'})

# Unimos este promedio a la tabla
rts = rts.merge(avg_lap_ms, on='RACEID', how='left')

# Imputamos los últimos nulos: Vueltas del piloto * Promedio de tiempo de esa carrera
rts['MILLISECONDS'] = rts['MILLISECONDS'].fillna(rts['LAPS'] * rts['AVG_MS_PER_LAP'])

# 6. LIMPIEZA TOTAL
# Si aún queda algo (carreras sin ningún dato de tiempo), ponemos 0 para llegar a 0 nulos.
rts['MILLISECONDS'] = rts['MILLISECONDS'].fillna(0)

# Borramos columnas auxiliares
rts.drop(columns=['MS_TOTAL_LT', 'AVG_MS_PER_LAP'], inplace=True)

print(f"Conteo final de nulos en MILLISECONDS: {rts['MILLISECONDS'].isna().sum()}")

