import pandas as pd
import numpy as np

# 1. Agrupamos PIT_STOPS para obtener la suma de milisegundos por carrera y piloto
# Usamos directamente las columnas 'milliseconds', 'RACEID' y 'DRIVERID'
pit_sums = ps.groupby(['RACEID', 'DRIVERID'])['MILLISECONDS'].sum().reset_index()

# 2. Hacemos el merge con rts
# Nota: Asegúrate de que los nombres de las columnas coincidan (ej: RACEID o raceId)
rts = rts.merge(pit_sums, left_on=['RACEID', 'DRIVERID'], right_on=['RACEID', 'DRIVERID'], how='left')

# 3. Función de conversión a formato de tiempo (hh:mm:ss.mmm)
def ms_to_f1(ms):
    if pd.isna(ms) or ms <= 0:
        return np.nan
    total_sec = ms / 1000
    h = int(total_sec // 3600)
    m = int((total_sec % 3600) // 60)
    s = total_sec % 60
    if h > 0:
        return f"{h}:{m:02d}:{s:06.3f}"[:-1]
    else:
        return f"{m:02d}:{s:06.3f}"[:-1]

# 4. Imputación directa en la columna TIME original
# Sumamos MILLISECONDS (pista) + MILLISECONDS (boxes) y rellenamos nulos
rts['TIME'] = rts['TIME'].fillna(
    (rts['MILLISECONDS_x'] + rts['MILLISECONDS_y'].fillna(0)).apply(ms_to_f1)
)

# 5. Eliminamos las columnas sobrantes del merge para mantener la estructura original
rts.drop(columns=['MILLISECONDS_y'], inplace=True)
rts.rename(columns={'MILLISECONDS_x': 'MILLISECONDS'}, inplace=True)

