# 1. Limpieza de datos (asegurar que sean numéricos)
rts['RACEID'] = pd.to_numeric(rts['RACEID'], errors='coerce')
rts['DRIVERID'] = pd.to_numeric(rts['DRIVERID'], errors='coerce')
